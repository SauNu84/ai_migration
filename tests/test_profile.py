#!/usr/bin/env python3
"""Phase 0 acceptance tests (SAU-303).

Validates that the profiling harness output (artifacts/profile.json) satisfies the
§8 input-side requirements and matches the ground-truth manifest:

  1. Reproducible schema profiled: >= 15 base tables, real FKs present.
  2. Every seeded hard column appears in the profile with the expected pg type signal.
  3. Statistics (null_rate, distinct_count) are computed for all columns.
  4. The ground-truth manifest is self-consistent (every entry references a real column).

Run (after scripts/setup.sh against a live Postgres):
    PGPORT=5599 PGPASSWORD=postgres python3 -m unittest tests.test_profile -v
If artifacts/profile.json is absent it is generated by invoking profile/profile.py;
if no database is reachable the DB-dependent tests skip with a clear message.
"""
from __future__ import annotations

import json
import subprocess
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ARTIFACT = ROOT / "artifacts" / "profile.json"
MANIFEST = ROOT / "ground_truth" / "hard_columns.json"

# Expected pg type signal per hard column: (predicate name, expected) checked against
# the profiled column record. Keyed by (table, column).
TYPE_SIGNALS = {
    ("app_user", "ssn_last4"):        {"udt": "bpchar", "char_max_len": 4},
    ("payment", "card_last4"):        {"udt": "bpchar", "char_max_len": 4},
    ("api_token", "token_hash"):      {"udt": "bpchar", "char_max_len": 64},
    ("app_user", "last_login_at"):    {"data_type": "timestamp without time zone"},
    ("org", "created_at"):            {"data_type": "timestamp with time zone"},
    ("invoice", "total_amount"):      {"numeric_precision": 14, "numeric_scale": 4},
    ("invoice", "tax_rate"):          {"numeric_precision": 9, "numeric_scale": 6},
    ("subscription", "mrr_cents"):    {"udt": "int8"},
    ("plan", "monthly_price"):        {"numeric_precision": 12, "numeric_scale": 2},
    ("product", "weight_kg"):         {"udt": "float4"},
    ("order_item", "discount_pct"):   {"numeric_precision": 5, "numeric_scale": 4},
    ("customer_order", "shipping_address"): {"udt": "jsonb"},
    ("product", "attributes"):        {"udt": "jsonb"},
    ("customer_order", "tags"):       {"udt": "_text"},
    ("product", "dimensions_cm"):     {"udt": "_numeric"},
    ("audit_log", "ip_address"):      {"udt": "inet"},
    ("customer_order", "legacy_total_text"): {"udt": "varchar", "char_max_len": 32},
    ("app_user", "email"):            {"udt": "varchar", "char_max_len": 320},
    ("warehouse", "location_lat"):    {"udt": "float8"},
}


def _ensure_profile():
    """Return parsed profile.json, generating it if needed; None if no DB reachable."""
    if not ARTIFACT.exists():
        try:
            subprocess.run(
                ["python3", str(ROOT / "profile" / "profile.py")],
                check=True, capture_output=True, text=True,
            )
        except Exception:
            return None
    try:
        return json.loads(ARTIFACT.read_text())
    except Exception:
        return None


class GroundTruthManifestTests(unittest.TestCase):
    """Manifest checks — no database required."""

    def setUp(self):
        self.manifest = json.loads(MANIFEST.read_text())

    def test_manifest_has_hard_columns_across_categories(self):
        cols = self.manifest["hard_columns"]
        self.assertGreaterEqual(len(cols), 15, "manifest should document >= 15 hard columns")
        cats = {c["category"] for c in cols}
        for needed in ("currency_precision", "timestamp_tz_distinction", "semi_structured",
                       "array", "pii_fixed_width", "no_native_target", "ambiguous_text_numeric"):
            self.assertIn(needed, cats, f"manifest missing category {needed}")

    def test_manifest_entries_are_well_formed(self):
        for c in self.manifest["hard_columns"]:
            for field in ("table", "column", "pg_type", "snowflake_target", "trap",
                          "assert", "confidence_floor"):
                self.assertIn(field, c, f"{c.get('column')} missing {field}")
            self.assertTrue(0.0 <= c["confidence_floor"] <= 1.0)


class ProfileArtifactTests(unittest.TestCase):
    """Profile-output checks — require a profiled database."""

    @classmethod
    def setUpClass(cls):
        cls.profile = _ensure_profile()
        cls.manifest = json.loads(MANIFEST.read_text())

    def setUp(self):
        if self.profile is None:
            self.skipTest("artifacts/profile.json not available and no DB reachable "
                          "— run scripts/setup.sh first")

    def _col(self, table, column):
        for t in self.profile["tables"]:
            if t["table"] == table:
                for c in t["columns"]:
                    if c["name"] == column:
                        return c
        return None

    def test_at_least_15_tables(self):
        self.assertGreaterEqual(self.profile["table_count"], 15)

    def test_foreign_keys_present(self):
        self.assertGreater(self.profile["fk_count"], 0)
        fk = self.profile["foreign_keys"][0]
        for k in ("table", "column", "ref_table", "ref_column"):
            self.assertIn(k, fk)

    def test_every_hard_column_present_with_expected_type(self):
        for entry in self.manifest["hard_columns"]:
            key = (entry["table"], entry["column"])
            col = self._col(*key)
            self.assertIsNotNone(col, f"hard column {key} missing from profile")
            for field, expected in TYPE_SIGNALS.get(key, {}).items():
                self.assertEqual(col.get(field), expected,
                                 f"{key}.{field}: expected {expected}, got {col.get(field)}")

    def test_stats_computed_for_all_columns(self):
        for t in self.profile["tables"]:
            for c in t["columns"]:
                self.assertIn("null_count", c)
                if t["row_count"] > 0 and c.get("null_rate") is not None:
                    self.assertGreaterEqual(c["null_rate"], 0.0)
                    self.assertLessEqual(c["null_rate"], 1.0)

    def test_seeded_nulls_detected(self):
        # readonly user (app_user id=3) has null full_name; invoice has null paid_at rows.
        self.assertGreaterEqual(self._col("app_user", "full_name")["null_count"], 1)
        self.assertGreaterEqual(self._col("invoice", "paid_at")["null_count"], 1)

    def test_fixed_width_pii_not_collapsed(self):
        # ssn_last4 distinct values include leading-zero strings — distinct_count > 1.
        self.assertGreaterEqual(self._col("app_user", "ssn_last4")["distinct_count"], 2)


if __name__ == "__main__":
    unittest.main(verbosity=2)
